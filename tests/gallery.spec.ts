import { test, expect } from "@playwright/test";
import sharp from "sharp";

test("public browsing, restricted writes, and persistent theme", async ({ page, request }) => {
 const errors: string[] = [];
 page.on("pageerror", error => errors.push(error.message));
 await page.goto("/");
 await expect(page.getByRole("heading", { name: "AI art", exact: true })).toBeVisible();
 await expect(page.getByText("No images yet")).toBeVisible();
 expect((await request.post("/api/images", { headers: { origin: "http://127.0.0.1:5187" } })).status()).toBe(403);
 expect((await request.patch("/api/images/00000000-0000-4000-8000-000000000000", { headers: { origin: "http://127.0.0.1:5187" }, data: { title: "No" } })).status()).toBe(403);
 expect((await request.delete("/api/images/00000000-0000-4000-8000-000000000000", { headers: { origin: "http://127.0.0.1:5187" } })).status()).toBe(403);
 await page.getByLabel("Color theme").selectOption("light");
 await page.reload();
 await expect(page.locator("html")).toHaveAttribute("data-theme", "light");
 await expect(page.getByText("No images yet")).toBeVisible();
 await page.screenshot({ path: "outputs/gallery-empty-desktop.png", fullPage: true });
 await page.setViewportSize({ width: 390, height: 844 });
 await page.getByLabel("Color theme").selectOption("dark");
 await page.screenshot({ path: "outputs/gallery-empty-mobile.png", fullPage: true });
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
 expect(errors).toEqual([]);
});

test("owner upload, metadata removal, edit, search, viewer, reload and delete", async ({ page, request }) => {
 const errors: string[] = [];
 page.on("pageerror", error => errors.push(error.message));
 const marker = "PRIVATE_METADATA_SHOULD_NOT_SHIP";
 const fixture = await sharp({ create: { width: 640, height: 400, channels: 3, background: "#8a78ad" } }).withExif({ IFD0: { Artist: marker } }).png().toBuffer();
 await page.goto("/signin-with-chatgpt?return_to=/manage");
 await expect(page.getByRole("heading", { name: "Manage gallery" })).toBeVisible();
 await expect(page.getByLabel("Choose images to upload")).toBeEnabled();
 await page.getByLabel("Choose images to upload").setInputFiles([{ name: "private-filename.png", mimeType: "image/png", buffer: fixture }]);
 await expect(page.getByText("1 of 1 uploaded")).toBeVisible({ timeout: 30000 });
 let listing = await (await request.get("/api/images")).json();
 expect(listing.total).toBe(1);
 const id = listing.items[0].id;
 expect(listing.items[0].title).toBe("Untitled");
 const image = await (await request.get(`/media/${id}/original`)).body();
 expect(image.includes(Buffer.from(marker))).toBe(false);
 expect((await sharp(image).metadata()).exif).toBeUndefined();
 const decoded = await sharp(image).metadata(); expect(decoded.width).toBe(640);
 await page.getByRole("button", { name: "Edit Untitled", exact: true }).click();
 await page.getByLabel("Title", { exact: true }).fill("Violet study");
 await page.getByLabel("Description", { exact: true }).fill("A local test image.");
 await page.getByLabel("Tags", { exact: true }).fill("abstract, violet");
 await page.getByRole("button", { name: "Save changes" }).click();
 await expect(page.getByRole("button", { name: "View Violet study", exact: true })).toBeVisible();
 await page.reload();
 await page.getByLabel("Search images", { exact: true }).fill("no-such-title");
 await expect(page.getByText("No images found")).toBeVisible();
 await page.getByLabel("Search images", { exact: true }).fill("violet");
 await expect(page.getByRole("button", { name: "View Violet study", exact: true })).toBeVisible();
 await page.getByRole("button", { name: "View Violet study", exact: true }).click();
 await expect(page.getByRole("dialog", { name: "Violet study" })).toBeVisible();
 await expect(page.getByText("640 × 400")).toBeVisible();
 await page.screenshot({ path: "outputs/gallery-viewer.png" });
 await page.keyboard.press("Escape");
 await expect(page.getByRole("dialog", { name: "Violet study" })).not.toBeVisible();
 await page.setViewportSize({ width: 390, height: 844 });
 await page.screenshot({ path: "outputs/gallery-manage-mobile.png", fullPage: true });
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
 expect((await page.request.post("/api/images", { headers: { origin: "https://example.invalid" } })).status()).toBe(403);
 const sameOrigin = await page.evaluate(async () => (await fetch("/api/images", { method: "POST" })).status);
 // Same-origin browser requests work only with the authenticated owner cookie.
 expect(sameOrigin).toBe(400);
 await page.getByRole("button", { name: "Edit Violet study", exact: true }).click();
 page.once("dialog", dialog => dialog.accept());
 await page.getByRole("button", { name: "Delete", exact: true }).click();
 await expect(page.getByText("No images found")).toBeVisible();
 expect((await request.get(`/media/${id}/original`)).status()).toBe(404);
 listing = await (await request.get("/api/images")).json(); expect(listing.total).toBe(0);
 expect(errors).toEqual([]);
});
